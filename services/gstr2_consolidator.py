class GSTR2Consolidator:
    """Consolidates GSTR-2A (ZIP/Excel) and GSTR-2B (Excel) returns into multi-sheet master workbooks."""

    SUMMARY_SHEET_NAMES: Set[str] = {
        "readme", "instructions", "itcavailable", "itcnotavailable", 
        "itcreversal", "itcrejected"
    }

    def __init__(self, log_callback: Optional[Callable[[str], None]] = None):
        self.log_callback = log_callback

    def log(self, message: str) -> None:
        if self.log_callback:
            try:
                self.log_callback(message)
            except Exception:
                pass
        else:
            try:
                print(message, flush=True)
            except Exception:
                try:
                    print(message.encode("ascii", "replace").decode("ascii"), flush=True)
                except Exception:
                    pass

    def extract_excel_from_zip(self, zip_path: str, temp_dir: str) -> Optional[str]:
        """Extracts the first .xlsx file inside a GSTR-2A ZIP archive to temp_dir."""
        try:
            with zipfile.ZipFile(zip_path, 'r') as zf:
                for name in zf.namelist():
                    if name.lower().endswith('.xlsx') and not name.startswith('__MACOSX') and not name.startswith('.'):
                        extracted_path = zf.extract(name, temp_dir)
                        return extracted_path
        except Exception as e:
            self.log(f"   ⚠️ [ZIP Extract Warning] Could not extract {os.path.basename(zip_path)}: {e}")
        return None

    def get_unique_sheets(self, excel_files: List[str], exclude_readme: bool = True) -> List[str]:
        """Scans all Excel workbooks to collect unique sheet names in order of appearance."""
        ordered_sheets: List[str] = []
        seen = set()

        for f_path in excel_files:
            try:
                wb = load_workbook(f_path, read_only=True)
                for s_name in wb.sheetnames:
                    if exclude_readme and s_name.lower().replace(" ", "").replace("_", "") in ["readme", "instructions"]:
                        continue
                    if s_name not in seen:
                        seen.add(s_name)
                        ordered_sheets.append(s_name)
                wb.close()
            except Exception as e:
                self.log(f"   ⚠️ [Warning] Could not inspect sheets of {os.path.basename(f_path)}: {e}")

        return ordered_sheets

    def _is_summary_sheet(self, sheet_name: str, ws=None) -> bool:
        """
        Determines if a sheet is an informational / summary overview sheet vs transaction invoice sheet.
        Uses canonical naming rules and dynamic header column sniffing for 100% future-proofing.
        """
        norm = sheet_name.lower().replace(" ", "").replace("_", "").replace("-", "")
        if norm in self.SUMMARY_SHEET_NAMES or "summary" in norm or "overview" in norm or "instruction" in norm or "readme" in norm:
            return True

        # If worksheet object is provided, dynamically verify if it contains invoice/transaction headers
        if ws is not None:
            transaction_keywords = [
                "gstin", "invoice", "note number", "document number", "bill of entry", 
                "icegate", "deductor", "supplier", "recipient"
            ]
            has_tx_header = False
            for r in range(1, min(10, ws.max_row + 1)):
                row_text = " ".join([str(ws.cell(r, c).value or "").lower() for c in range(1, min(15, ws.max_column + 1))])
                if any(kw in row_text for kw in transaction_keywords):
                    has_tx_header = True
                    break
            # If no transaction column headers are found, safely treat as a summary overview
            if not has_tx_header:
                return True

        return False

    def _detect_data_start_row(self, ws) -> int:
        """
        Detects the row index where transaction records begin (typically Row 7 in GST Portal 2A/2B).
        Dynamically locates the end of table column headers (e.g. GSTIN, Invoice, Note, Bill of entry, Taxable, etc.).
        """
        last_header_row = 6
        header_keywords = [
            "gstin", "supplier", "trade", "legal name", "invoice", "note", "document", 
            "taxable", "integrated tax", "central tax", "state/ut tax", "cess", "place of supply",
            "icegate", "bill of entry", "deductor", "eligibility", "rate"
        ]

        found_header = False
        for r in range(1, min(12, ws.max_row + 1)):
            row_text = " ".join([str(ws.cell(r, c).value or "").lower() for c in range(1, min(15, ws.max_column + 1))])
            if any(kw in row_text for kw in header_keywords):
                found_header = True
                last_header_row = r

        if found_header:
            return last_header_row + 1
        return 7

    @staticmethod
    def _is_valid_transaction_row(cells_list) -> bool:
        """
        Validates if a row contains genuine transaction data based on 3 deterministic criteria:
        1. 15-character GSTIN regex (e.g. 29ABBFA8884E1Z5).
        2. Valid Date format (DD/MM/YYYY, DD-MM-YYYY or datetime object).
        3. Numeric Tax / Invoice Amount (int or float != 0).
        """
        import re
        import datetime
        for c in cells_list:
            v = c.value
            if v is None or v == "":
                continue
            if isinstance(v, (int, float)) and v != 0:
                return True
            if isinstance(v, (datetime.date, datetime.datetime)):
                return True
            v_str = str(v).strip()
            # 15-character GSTIN pattern
            if re.search(r'\b[0-9]{2}[A-Z]{5}[0-9]{4}[A-Z]{1}[1-9A-Z]{1}Z[0-9A-Z]{1}\b', v_str):
                return True
            # Date pattern DD/MM/YYYY or DD-MM-YYYY
            if re.match(r'^\d{2}[/-]\d{2}[/-]\d{4}$', v_str):
                return True
        return False

    def _consolidate_workbook_list(
        self,
        excel_files: List[str],
        output_filepath: str,
        return_label: str,
        progress_callback: Optional[Callable[[float, str], None]] = None
    ) -> str:
        """Core Excel Consolidator engine that merges multiple workbooks into a single file."""
        if not excel_files:
            raise ValueError(f"No {return_label} Excel files found to consolidate.")

        self.log(f"\n[{return_label} Consolidator] Scanning {len(excel_files)} return file(s)...")
        unique_sheets = self.get_unique_sheets(excel_files, exclude_readme=False)
        self.log(f"   • Detected {len(unique_sheets)} unique sheet(s): {', '.join(unique_sheets[:6])}{'...' if len(unique_sheets) > 6 else ''}")

        target_wb = Workbook()
        target_wb.remove(target_wb.active)  # Remove default initial sheet

        for sheet_name in unique_sheets:
            target_wb.create_sheet(sheet_name)

        # Track extraction statistics per sheet: {sheet_name: {"type": ..., "rows": count, "status": ...}}
        sheet_stats: Dict[str, Dict[str, Any]] = {}
        for s_name in unique_sheets:
            is_sum = self._is_summary_sheet(s_name)
            sheet_stats[s_name] = {
                "type": "Summary / Overview" if is_sum else "Transaction Data",
                "rows": 0,
                "status": "Initialized"
            }

        total_files = len(excel_files)
        for i, file_path in enumerate(excel_files, start=1):
            file_name = os.path.basename(file_path)
            self.log(f"   [{i}/{total_files}] Processing: {file_name}")

            try:
                source_wb = load_workbook(file_path)
            except Exception as e:
                self.log(f"   ⚠️ [Error loading {file_name}] {e}")
                continue

            for sheet_name in source_wb.sheetnames:
                if sheet_name not in target_wb.sheetnames:
                    continue

                source_sheet = source_wb[sheet_name]
                target_sheet = target_wb[sheet_name]
                is_summary = self._is_summary_sheet(sheet_name, ws=source_sheet)
                is_sheet_brand_new = (target_sheet.max_row == 1 and target_sheet.cell(1, 1).value is None)

                # Update sheet type if dynamic inspection refined it
                if is_summary:
                    sheet_stats[sheet_name]["type"] = "Summary / Overview"
                else:
                    sheet_stats[sheet_name]["type"] = "Transaction Data"

                if is_summary or is_sheet_brand_new:
                    # ─── CASE A: Full Sheet Copy (First Month or Summary Sheets) ───
                    if is_sheet_brand_new:
                        data_start_row = 1
                    else:
                        data_start_row = target_sheet.max_row + 2  # 1 blank row gap between files

                    # Count rows extracted (excluding header rows if it is a transaction sheet on Month 1)
                    if is_summary:
                        sheet_stats[sheet_name]["rows"] += source_sheet.max_row
                    else:
                        src_header_end = self._detect_data_start_row(source_sheet) - 1
                        m1_tx_count = 0
                        for r_idx in range(src_header_end + 1, source_sheet.max_row + 1):
                            row_cells = [source_sheet.cell(r_idx, c) for c in range(1, source_sheet.max_column + 1)]
                            if self._is_valid_transaction_row(row_cells):
                                m1_tx_count += 1
                        sheet_stats[sheet_name]["rows"] += m1_tx_count

                    # Copy cells row by row
                    for r_idx, row in enumerate(source_sheet.iter_rows(values_only=False), start=1):
                        target_row = data_start_row + r_idx - 1

                        # Column A is reserved for the source file name
                        target_sheet.cell(row=target_row, column=1, value=file_name)

                        for c_idx, cell in enumerate(row, start=1):
                            target_cell = target_sheet.cell(
                                row=target_row,
                                column=c_idx + 1,  # Shift data columns to the right by 1
                                value=cell.value
                            )
                            if cell.has_style:
                                target_cell.font = copy.copy(cell.font)
                                target_cell.border = copy.copy(cell.border)
                                target_cell.fill = copy.copy(cell.fill)
                                target_cell.number_format = cell.number_format
                                target_cell.alignment = copy.copy(cell.alignment)

                    # Recreate merged cells with offset
                    for merged_range in source_sheet.merged_cells.ranges:
                        new_min_row = merged_range.min_row + data_start_row - 1
                        new_max_row = merged_range.max_row + data_start_row - 1
                        new_min_col = merged_range.min_col + 1
                        new_max_col = merged_range.max_col + 1

                        target_sheet.merge_cells(
                            start_row=new_min_row,
                            start_column=new_min_col,
                            end_row=new_max_row,
                            end_column=new_max_col
                        )

                    # Copy row heights
                    for row_idx, dim in source_sheet.row_dimensions.items():
                        if dim.height is not None:
                            target_sheet.row_dimensions[row_idx + data_start_row - 1].height = dim.height

                    # Copy column widths
                    for col_letter, dim in source_sheet.column_dimensions.items():
                        if dim.width is not None:
                            col_idx = column_index_from_string(col_letter)
                            new_col_idx = col_idx + 1
                            new_col_letter = get_column_letter(new_col_idx)
                            target_sheet.column_dimensions[new_col_letter].width = max(
                                target_sheet.column_dimensions[new_col_letter].width or 0,
                                dim.width
                            )

                else:
                    # ─── CASE B: Transaction Sheet Deduplication (Months 2..N) ───
                    # Skip header rows (Rows 1 to data_start_row - 1), append only data rows with 1 blank row gap
                    src_data_start = self._detect_data_start_row(source_sheet)
                    
                    # Collect only valid transaction rows
                    valid_tx_rows = []
                    if source_sheet.max_row >= src_data_start:
                        for r_idx in range(src_data_start, source_sheet.max_row + 1):
                            row_cells = [source_sheet.cell(r_idx, c) for c in range(1, source_sheet.max_column + 1)]
                            if self._is_valid_transaction_row(row_cells):
                                valid_tx_rows.append((r_idx, row_cells))

                    if valid_tx_rows:
                        sheet_stats[sheet_name]["rows"] += len(valid_tx_rows)
                        # Add 1 blank separating row between months
                        target_data_start = target_sheet.max_row + 2

                        # Copy only genuine transaction rows
                        for offset_idx, (r_idx, row) in enumerate(valid_tx_rows):
                            target_row = target_data_start + offset_idx

                            # Column A is reserved for the source file name
                            target_sheet.cell(row=target_row, column=1, value=file_name)

                            for c_idx, cell in enumerate(row, start=1):
                                target_cell = target_sheet.cell(
                                    row=target_row,
                                    column=c_idx + 1,
                                    value=cell.value
                                )
                                if cell.has_style:
                                    target_cell.font = copy.copy(cell.font)
                                    target_cell.border = copy.copy(cell.border)
                                    target_cell.fill = copy.copy(cell.fill)
                                    target_cell.number_format = cell.number_format
                                    target_cell.alignment = copy.copy(cell.alignment)

                            # Copy row height if present
                            if r_idx in source_sheet.row_dimensions:
                                dim = source_sheet.row_dimensions[r_idx]
                                if dim.height is not None:
                                    target_sheet.row_dimensions[target_row].height = dim.height

                        # Recreate merged cells for data rows
                        row_offset = target_data_start - src_data_start
                        for merged_range in source_sheet.merged_cells.ranges:
                            if merged_range.min_row >= src_data_start:
                                target_sheet.merge_cells(
                                    start_row=merged_range.min_row + row_offset,
                                    start_column=merged_range.min_col + 1,
                                    end_row=merged_range.max_row + row_offset,
                                    end_column=merged_range.max_col + 1
                                )

            source_wb.close()

            if progress_callback:
                progress_callback(i / total_files, file_name)

        # Set Column A header and width for all sheets
        for sheet in target_wb.worksheets:
            sheet.column_dimensions['A'].width = 32

        # Finalize status labels for summary sheet
        for s_name, s_info in sheet_stats.items():
            r_cnt = s_info["rows"]
            if s_info["type"] == "Summary / Overview":
                s_info["status"] = "Overview Table"
            elif r_cnt > 0:
                s_info["status"] = f"Active ({r_cnt} Records)"
            else:
                s_info["status"] = "No Records Found"

        # ─── Create Master Consolidation Summary Sheet at Index 0 ─────────────
        self._create_consolidation_summary_sheet(
            target_wb=target_wb,
            return_label=return_label,
            total_files=total_files,
            stats=sheet_stats
        )

        # Apply official author metadata
        apply_author_metadata(target_wb)

        os.makedirs(os.path.dirname(os.path.abspath(output_filepath)), exist_ok=True)
        target_wb.save(output_filepath)
        target_wb.close()

        self.log(f"✅ [{return_label} Consolidator] Successfully created master workbook:\n   {output_filepath}")
        return output_filepath

    def _create_consolidation_summary_sheet(
        self,
        target_wb: Workbook,
        return_label: str,
        total_files: int,
        stats: Dict[str, Dict[str, Any]]
    ) -> None:
        """
        Creates a dedicated 'Consolidation Summary' master sheet as Sheet Index 0:
        Lists all extracted sheets, classification type (Summary vs Transaction),
        and total data rows extracted (excluding stripped header rows).
        """
        from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
        from openpyxl.utils import get_column_letter

        # Create as the very first sheet
        ws_summary = target_wb.create_sheet(title="Consolidation Summary", index=0)

        # Style Definitions
        NAVY_FILL = PatternFill(start_color="1A365D", end_color="1A365D", fill_type="solid")
        HEADER_FONT = Font(name="Segoe UI", size=11, bold=True, color="FFFFFF")
        TITLE_FONT = Font(name="Segoe UI", size=14, bold=True, color="1A365D")
        SUB_FONT = Font(name="Segoe UI", size=10, italic=True, color="4B5563")
        BOLD_FONT = Font(name="Segoe UI", size=10, bold=True, color="0F172A")
        DATA_FONT = Font(name="Segoe UI", size=10, color="1E293B")
        TOTAL_FILL = PatternFill(start_color="F1F5F9", end_color="F1F5F9", fill_type="solid")

        THIN_SIDE = Side(style="thin", color="CBD5E1")
        THIN_BORDER = Border(left=THIN_SIDE, right=THIN_SIDE, top=THIN_SIDE, bottom=THIN_SIDE)
        DOUBLE_BOTTOM = Side(style="double", color="0F172A")
        TOP_THIN = Side(style="thin", color="0F172A")
        TOTAL_BORDER = Border(left=THIN_SIDE, right=THIN_SIDE, top=TOP_THIN, bottom=DOUBLE_BOTTOM)

        # 1. Header Banner
        ws_summary["A1"] = f"{return_label} Master Consolidation Summary"
        ws_summary["A1"].font = TITLE_FONT
        ws_summary["A2"] = f"Generated by Vertex | Return Files Consolidated: {total_files} | Total Sheets: {len(stats)}"
        ws_summary["A2"].font = SUB_FONT

        # 2. Table Headers (Row 4)
        headers = ["Sl. No.", "Worksheet Name", "Classification Type", "Extracted Data Rows Count", "Status"]
        ws_summary.row_dimensions[4].height = 26

        for col_idx, h_text in enumerate(headers, start=1):
            cell = ws_summary.cell(row=4, column=col_idx, value=h_text)
            cell.fill = NAVY_FILL
            cell.font = HEADER_FONT
            cell.alignment = Alignment(horizontal="center" if col_idx in [1, 3, 4, 5] else "left", vertical="center")

        # 3. Data Rows
        start_row = 5
        for sl_no, (s_name, s_info) in enumerate(stats.items(), start=1):
            curr_row = start_row + sl_no - 1
            ws_summary.row_dimensions[curr_row].height = 20

            c_type = s_info.get("type", "Transaction Data")
            row_count = s_info.get("rows", 0)
            status_text = s_info.get("status", f"{row_count} Records" if row_count > 0 else "No Records Found")

            row_values = [sl_no, s_name, c_type, row_count, status_text]
            for col_idx, val in enumerate(row_values, start=1):
                cell = ws_summary.cell(row=curr_row, column=col_idx, value=val)
                cell.font = DATA_FONT
                cell.border = THIN_BORDER
                if col_idx in [1, 3, 5]:
                    cell.alignment = Alignment(horizontal="center", vertical="center")
                elif col_idx == 4:
                    cell.alignment = Alignment(horizontal="right", vertical="center")
                    cell.number_format = "#,##0"
                else:
                    cell.alignment = Alignment(horizontal="left", vertical="center")

        # 4. Total Summary Row
        end_data_row = start_row + len(stats) - 1
        total_row_idx = end_data_row + 1
        ws_summary.row_dimensions[total_row_idx].height = 24

        ws_summary.cell(row=total_row_idx, column=1, value="Total").font = BOLD_FONT
        ws_summary.cell(row=total_row_idx, column=1).alignment = Alignment(horizontal="center", vertical="center")
        
        sum_cell = ws_summary.cell(row=total_row_idx, column=4, value=f"=SUM(D{start_row}:D{end_data_row})")
        sum_cell.font = BOLD_FONT
        sum_cell.alignment = Alignment(horizontal="right", vertical="center")
        sum_cell.number_format = "#,##0"

        for col_idx in range(1, 6):
            cell = ws_summary.cell(row=total_row_idx, column=col_idx)
            cell.fill = TOTAL_FILL
            cell.border = TOTAL_BORDER

        # 5. Column Widths
        for col in ws_summary.columns:
            col_letter = get_column_letter(col[0].column)
            max_len = max(len(str(cell.value or "")) for cell in col)
            ws_summary.column_dimensions[col_letter].width = max(max_len + 6, 16)

        # Set as active sheet
        target_wb.active = ws_summary

    def consolidate_gstr2a(
        self,
        files_or_zips: List[str],
        output_filepath: str,
        progress_callback: Optional[Callable[[float, str], None]] = None
    ) -> str:
        """
        Consolidates GSTR-2A return files. Automatically unzips any .zip archives
        to retrieve internal .xlsx return sheets, then runs full multi-sheet consolidation.
        """
        temp_dir = tempfile.mkdtemp(prefix="vx_gstr2a_")
        excel_files_to_process: List[str] = []

        try:
            self.log(f"[GSTR-2A Consolidator] Preparing {len(files_or_zips)} GSTR-2A return source(s)...")
            for f in sorted(files_or_zips):
                fname = os.path.basename(f).lower()
                if "consolidat" in fname:
                    continue
                if f.lower().endswith(".zip"):
                    extracted_xlsx = self.extract_excel_from_zip(f, temp_dir)
                    if extracted_xlsx and os.path.exists(extracted_xlsx):
                        excel_files_to_process.append(extracted_xlsx)
                    else:
                        self.log(f"   ⚠️ [GSTR-2A] No valid .xlsx found inside ZIP: {os.path.basename(f)}")
                elif f.lower().endswith(".xlsx") or f.lower().endswith(".xls"):
                    excel_files_to_process.append(f)

            if not excel_files_to_process:
                raise ValueError("No valid GSTR-2A Excel workbooks could be extracted or found.")

            res = self._consolidate_workbook_list(
                excel_files=excel_files_to_process,
                output_filepath=output_filepath,
                return_label="GSTR-2A",
                progress_callback=progress_callback
            )
            return res

        finally:
            # Clean up temporary unzipped files
            try:
                shutil.rmtree(temp_dir, ignore_errors=True)
            except Exception:
                pass

    def consolidate_gstr2b(
        self,
        excel_files: List[str],
        output_filepath: str,
        progress_callback: Optional[Callable[[float, str], None]] = None
    ) -> str:
        """Consolidates GSTR-2B monthly Excel returns across all sheets."""
        valid_excels = [
            f for f in sorted(excel_files) 
            if (f.lower().endswith(".xlsx") or f.lower().endswith(".xls")) and "consolidat" not in os.path.basename(f).lower()
        ]
        if not valid_excels:
            raise ValueError("No valid GSTR-2B Excel workbooks found.")

        return self._consolidate_workbook_list(
            excel_files=valid_excels,
            output_filepath=output_filepath,
            return_label="GSTR-2B",
            progress_callback=progress_callback
        )
